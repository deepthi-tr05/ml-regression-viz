// ── LWLR Seeded RNG ─────────────────────────────────────
let lwlrSeed = 42;
function seededRand() {
  lwlrSeed = (lwlrSeed * 1664525 + 1013904223) & 0xffffffff;
  return (lwlrSeed >>> 0) / 4294967296;
}
function resetLwlrSeed(s = 42) { lwlrSeed = s; }

function generateLwlrData(sigma = 0.2, n = 100) {
  resetLwlrSeed(42);
  const X = [], y = [];
  for (let i = 0; i < n; i++) {
    const xi = -3 + 6 * i / (n - 1);
    const u1 = seededRand(), u2 = seededRand();
    const noise = Math.sqrt(-2 * Math.log(Math.max(u1, 1e-10))) * Math.cos(2 * Math.PI * u2);
    X.push(xi);
    y.push(Math.sin(xi) + sigma * noise);
  }
  return { X, y };
}
